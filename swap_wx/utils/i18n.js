function getLang() {
  try {
    return wx.getStorageSync(LANG_KEY) || 'zh';
  } catch (e) {
    return 'zh';
  }
}

function setLang(lang) {
  try {
    wx.setStorageSync(LANG_KEY, lang === 'en' ? 'en' : 'zh');
  } catch (e) { }
}

/**
 * 取当前语言的整本字典（供 wxml 绑定 {{t.key}}）
 */
function dictFor(lang) {
  return dict[lang || getLang()] || dict.zh;
}

/**
 * 取单条文案；支持 {{n}} 占位符：t('list_count', { n: 3 })
 */
function t(key, vars) {
  let text = dictFor()[key] || dict.zh[key] || key;
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      text = text.replace(new RegExp('\\{\\{' + k + '\\}\\}', 'g'), vars[k]);
    });
  }
  return text;
}

/**
 * 给页面注入字典：onLoad / onShow 里调用 i18n.apply(this)
 * wxml 中即可使用 {{t.key}}；切换语言后重新 apply 并刷新页面数据
 */
function apply(page) {
  page.setData({ t: dictFor(), _lang: getLang() });
}

/**
 * 同步底部 tabBar 文案（语言切换后调用）
 */
function applyTabBar() {
  if (!wx.setTabBarItem) return;
  // app.json 已启用 custom tabBar，setTabBarItem 仅作降级兜底
  wx.setTabBarItem({ index: 0, text: t('tab_home'), fail: () => {} });
  wx.setTabBarItem({ index: 1, text: t('tab_chats'), fail: () => {} });
  wx.setTabBarItem({ index: 2, text: t('tab_profile'), fail: () => {} });
}

module.exports = {
  getLang: getLang,
  setLang: setLang,
  dictFor: dictFor,
  t: t,
  apply: apply,
  applyTabBar: applyTabBar
};
